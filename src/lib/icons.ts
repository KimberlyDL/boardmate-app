/**
 * Lucide icons as data URLs, for the few Ionic APIs that take an icon string instead of
 * a component (toasts, alerts). Everywhere else, use the components from 'lucide-vue-next'.
 */
const PATHS = {
  'circle-check': '<circle cx="12" cy="12" r="10"/><path d="m9 12 2 2 4-4"/>',
  'circle-alert': '<circle cx="12" cy="12" r="10"/><line x1="12" x2="12" y1="8" y2="12"/><line x1="12" x2="12.01" y1="16" y2="16"/>',
  info: '<circle cx="12" cy="12" r="10"/><path d="M12 16v-4"/><path d="M12 8h.01"/>',
  'refresh-cw': '<path d="M3 12a9 9 0 0 1 9-9 9.75 9.75 0 0 1 6.74 2.74L21 8"/><path d="M21 3v5h-5"/><path d="M21 12a9 9 0 0 1-9 9 9.75 9.75 0 0 1-6.74-2.74L3 16"/><path d="M8 16H3v5"/>',
} as const

export type DataIconName = keyof typeof PATHS

export function lucideDataUrl(name: DataIconName): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${PATHS[name]}</svg>`
  // Not URI-encoded: ion-icon reads ";utf8," data URLs as raw SVG markup (the format Ionicons ships).
  return `data:image/svg+xml;utf8,${svg}`
}
